ROOT = Path("/kaggle/working/axisrepo")
for rel, b64 in FILES.items():
    raw = base64.b64decode(b64)
    want = EXPECTED[rel]
    got = hashlib.sha256(raw).hexdigest()
    if got != want:
        raise SystemExit(f"FATAL: payload {{rel}} sha256 {{got}} != {{want}}")
    p = ROOT / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_bytes(raw)
    print(f"  ok  {{rel:<24}} {{len(raw):>7}} B  {{got[:16]}}")
print(f"\\n  {{len(FILES)}} payloads verified and written to {{ROOT}}")
